"""Validate and embed API documentation as deterministic, flash-only assets.

This command only writes the generated local header. It does not contact or
update any device. Run before compiling the smart firmware variant.
"""
from __future__ import annotations

from pathlib import Path
import gzip
import json

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "esphome/api"
TARGET = ROOT / "esphome/api_assets.h"


def validate_document(document: dict) -> None:
    assert document.get("openapi") == "3.0.3"
    assert document.get("servers") == [{"url": "/api/v1", "description": "Mesmo ESP32 que hospeda esta documentação."}]
    assert document.get("security") == []
    expected_methods = {
        "/": {"get"}, "/capabilities": {"get"}, "/state": {"get"},
        "/telemetry": {"get"}, "/settings": {"get", "post"},
        "/control": {"get"}, "/history": {"get"}, "/sessions": {"get"},
        "/periods": {"get"}, "/diagnostics": {"get"}, "/health": {"get"},
        "/temperature": {"post"}, "/favorite": {"post"},
        "/preferences": {"post"}, "/control/cancel": {"post"},
        "/device/restart": {"post"},
    }
    assert {path: set(item) for path, item in document["paths"].items()} == expected_methods
    methods = []

    def visit(value):
        if isinstance(value, dict):
            if "$ref" in value:
                reference = value["$ref"]
                assert reference.startswith("#/"), reference
                cursor = document
                for token in reference[2:].split("/"):
                    cursor = cursor[token.replace("~1", "/").replace("~0", "~")]
            for nested in value.values():
                visit(nested)
        elif isinstance(value, list):
            for nested in value:
                visit(nested)

    visit(document)
    for path, item in document["paths"].items():
        assert path.startswith("/")
        for method, operation in item.items():
            assert method in ("get", "post"), (path, method)
            methods.append(method)
            assert operation["responses"]
            if method == "post":
                body = operation["requestBody"]
                assert body["required"] and body["x-max-content-length"] == 2048
                assert list(body["content"]) == ["application/json"]
                assert "202" in operation["responses"]
    assert methods.count("get") == sum("get" in value for value in expected_methods.values())
    assert methods.count("post") == sum("post" in value for value in expected_methods.values())


def main() -> None:
    document = json.loads((SOURCE / "openapi.json").read_text(encoding="utf-8"))
    validate_document(document)
    html = (SOURCE / "index.html").read_text(encoding="utf-8")
    assert "<script" not in html.lower() and "<form" not in html.lower()
    assert 'name="viewport"' in html and "/api/openapi.json" in html
    files = [
        ("documentation", "index.html", "text/html; charset=utf-8", ("/api", "/api/", "/api/docs")),
        ("openapi", "openapi.json", "application/json; charset=utf-8", ("/api/openapi.json",)),
    ]
    lines = ["// Generated by analysis/embed_api_assets.py. Do not edit.", "#pragma once",
             "#include <cstddef>", "#include <cstdint>", "#include <cstring>",
             "namespace rinnai_api_assets {",
             "struct Asset { const char *path; const char *type; const uint8_t *data; size_t size; bool compressed; };"]
    rows = []
    sizes = {}
    for symbol, filename, mime, routes in files:
        raw = (SOURCE / filename).read_bytes()
        body = gzip.compress(raw, compresslevel=9, mtime=0)
        assert gzip.decompress(body) == raw
        sizes[filename] = {"source_bytes": len(raw), "flash_bytes": len(body)}
        lines.append(f"inline constexpr uint8_t {symbol}[] = {{")
        for offset in range(0, len(body), 24):
            lines.append("  " + ",".join(f"0x{byte:02x}" for byte in body[offset:offset + 24]) + ",")
        lines.append("};")
        for route in routes:
            rows.append(f'  {{"{route}", "{mime}", {symbol}, sizeof({symbol}), true}},')
    lines.extend(["inline constexpr Asset ASSETS[] = {", *rows, "};",
                  "inline const Asset *find(const char *path) {",
                  "  for (const auto &asset : ASSETS) if (std::strcmp(path, asset.path) == 0) return &asset;",
                  "  return nullptr;", "}", "}  // namespace rinnai_api_assets", ""])
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps({"passed": True, "paths": len(document["paths"]),
                      "schemas": len(document["components"]["schemas"]), "routes": len(rows),
                      "assets": sizes, "total_flash_bytes": sum(item["flash_bytes"] for item in sizes.values())},
                     ensure_ascii=False))


if __name__ == "__main__":
    main()
