// Host-only regression tests. No ESP-IDF, network, UART or GPIO dependencies.
// Build as C++17; generated .obj/.exe files belong outside the source tree.
#include <cstdint>

static uint32_t fake_ms = 0;
#define RINNAI_TELEMETRY_MILLIS() fake_ms
#include "../esphome/rinnai_telemetry.h"

#include <cstdlib>
#include <iostream>
#include <limits>
#include <utility>

using Bytes = std::vector<uint8_t>;
using Parser = rinnai_telemetry::detail::Parser;

static unsigned checks = 0;
#define CHECK(condition) do { ++checks; if (!(condition)) { \
  std::cerr << __func__ << ':' << __LINE__ << ": " #condition "\n"; \
  std::exit(EXIT_FAILURE); } } while (false)

// These are exact hardware captures, not frames generated by the parser.
static const Bytes OUTLET{
    0x02, 0xF6, '0', '6', '0', '4', '0', '2', '1', 'E', '0', '8', 0x03, '0', '3', 0x0D};
static const Bytes INLET{
    0x02, 0xF6, '0', '6', '0', '6', '0', '2', 'D', '3', '0', '8', 0x03, '0', '6', 0x0D};
static const Bytes QUERY_ECHO{
    0x02, 0xF6, '0', '6', '0', '4', '0', '2', 0x03, '2', '5', 0x0D};

static void fix_checksum(Bytes &frame) {
  uint8_t sum = 0;
  for (size_t i = 1; i <= 12; ++i)
    sum = static_cast<uint8_t>(sum + frame[i]);
  const char *hex = "0123456789ABCDEF";
  frame[13] = static_cast<uint8_t>(hex[sum >> 4]);
  frame[14] = static_cast<uint8_t>(hex[sum & 15]);
}

static void real_captures() {
  Parser p;
  fake_ms = 1000;
  p.request_started(0x0604);
  fake_ms = 1045;
  const auto outlet = p.feed(OUTLET);
  CHECK(outlet.size() == 1);
  CHECK(outlet[0].address == 0x0604);
  CHECK(outlet[0].raw == 2078);
  CHECK(outlet[0].data_hex == "1E08");
  CHECK(outlet[0].rtt_ms == 45);
  CHECK(!p.pending());
  CHECK(p.valid_frames() == 1);
  CHECK(p.last_seen(0x0604) == 1045);
  CHECK(p.last_seen(0x0606) == 0);
  CHECK(p.last_valid_ms() == 1045);
  CHECK(p.last_rtt_ms() == 45);
  fake_ms = 4000;
  p.request_started(0x0606);
  fake_ms = 4020;
  const auto inlet = p.feed(INLET);
  CHECK(inlet.size() == 1);
  CHECK(inlet[0].address == 0x0606);
  CHECK(inlet[0].raw == 2259);
  CHECK(inlet[0].data_hex == "D308");
  CHECK(p.valid_frames() == 2);
  CHECK(p.bad_frames() == 0);
  CHECK(p.stale_frames() == 0);
}

static void every_two_chunk_split() {
  for (size_t split = 1; split < OUTLET.size(); ++split) {
    Parser p;
    fake_ms = 2000;
    p.request_started(0x0604);
    CHECK(p.feed(Bytes(OUTLET.begin(), OUTLET.begin() + split)).empty());
    CHECK(p.pending());
    fake_ms = 2030;
    const auto readings = p.feed(Bytes(OUTLET.begin() + split, OUTLET.end()));
    CHECK(readings.size() == 1);
    CHECK(readings[0].raw == 2078);
    CHECK(readings[0].rtt_ms == 30);
    CHECK(p.bad_frames() == 0);
  }
}

static void noise_echo_and_resynchronization() {
  Parser p;
  fake_ms = 3000;
  p.request_started(0x0604);
  CHECK(p.feed(Bytes{0x00, 0xFF, 0x0D, 0x01}).empty());
  CHECK(p.bad_frames() == 0);
  CHECK(p.feed(QUERY_ECHO).empty());
  CHECK(p.bad_frames() == 1);
  CHECK(p.pending());
  // A new STX must replace an incomplete candidate, then support single bytes.
  CHECK(p.feed(Bytes{0x02, 0xF6, '0'}).empty());
  unsigned received = 0;
  for (const uint8_t value : OUTLET) {
    ++fake_ms;
    received += static_cast<unsigned>(p.feed(Bytes{value}).size());
  }
  CHECK(received == 1);
  CHECK(p.bad_frames() == 2);
  CHECK(p.valid_frames() == 1);
  // A second valid frame with no pending request must not publish twice.
  CHECK(p.feed(OUTLET).empty());
  CHECK(p.stale_frames() == 1);
  CHECK(p.valid_frames() == 1);

  Parser bounded;
  bounded.request_started(0x0604);
  Bytes long_noise(1000, 'A');
  long_noise.insert(long_noise.begin(), 0x02);
  long_noise.push_back(0x0D);
  CHECK(bounded.feed(long_noise).empty());
  CHECK(bounded.bad_frames() == 1);
  CHECK(bounded.feed(OUTLET).size() == 1);
}

static void malformed_frames() {
  // Fix checksums after structural edits, so each specific gate is exercised.
  const std::array<std::pair<size_t, uint8_t>, 5> changes{{
      {1, 0xF7}, {7, '3'}, {12, 0x04}, {5, '5'}, {8, 'Z'}}};
  for (const auto &change : changes) {
    Parser p;
    fake_ms = 5000;
    p.request_started(0x0604);
    auto frame = OUTLET;
    frame[change.first] = change.second;
    fix_checksum(frame);
    CHECK(p.feed(frame).empty());
    CHECK(p.bad_frames() == 1);
    CHECK(p.pending());
    CHECK(p.valid_frames() == 0);
    CHECK(p.feed(OUTLET).size() == 1);
  }
  Parser checksum;
  checksum.request_started(0x0604);
  auto frame = OUTLET;
  frame[14] = '4';
  CHECK(checksum.feed(frame).empty());
  CHECK(checksum.bad_frames() == 1);
  CHECK(checksum.pending());

  Parser missing_stx;
  missing_stx.request_started(0x0604);
  CHECK(missing_stx.feed(Bytes(OUTLET.begin() + 1, OUTLET.end())).empty());
  CHECK(missing_stx.valid_frames() == 0);
  CHECK(missing_stx.pending());
}

static void pending_address_and_stale() {
  Parser p;
  fake_ms = 6000;
  CHECK(p.feed(OUTLET).empty());
  CHECK(p.stale_frames() == 1);
  CHECK(p.last_seen(0x0604) == 0);
  p.request_started(0x0604);
  p.request_started(0x0606);  // Must not replace the first transaction.
  CHECK(p.rejected_requests() == 1);
  CHECK(p.feed(INLET).empty());
  CHECK(p.stale_frames() == 2);
  CHECK(p.bad_frames() == 0);
  CHECK(p.pending());
  CHECK(p.feed(OUTLET).size() == 1);
  p.request_started(0xFFFF);
  CHECK(!p.pending());
  CHECK(p.rejected_requests() == 2);
  CHECK(p.last_seen(0xFFFF) == 0);

  Parser consecutive;
  consecutive.request_started(0x0604);
  Bytes two = OUTLET;
  two.insert(two.end(), OUTLET.begin(), OUTLET.end());
  CHECK(consecutive.feed(two).size() == 1);
  CHECK(consecutive.valid_frames() == 1);
  CHECK(consecutive.stale_frames() == 1);
}

static void timeout_boundaries() {
  Parser p;
  fake_ms = 10000;
  p.request_started(0x0604);
  fake_ms = 10499;
  CHECK(!p.timeout_check());
  CHECK(p.pending());
  fake_ms = 10500;
  CHECK(p.timeout_check());
  CHECK(!p.pending());
  CHECK(p.timeouts() == 1);
  CHECK(!p.timeout_check());
  CHECK(p.timeouts() == 1);
  CHECK(p.feed(OUTLET).empty());
  CHECK(p.stale_frames() == 1);

  Parser on_feed;
  fake_ms = 11000;
  on_feed.request_started(0x0604);
  CHECK(on_feed.feed(Bytes(OUTLET.begin(), OUTLET.begin() + 8)).empty());
  fake_ms = 11500;
  CHECK(on_feed.feed(Bytes(OUTLET.begin() + 8, OUTLET.end())).empty());
  CHECK(on_feed.timeouts() == 1);
  CHECK(on_feed.valid_frames() == 0);
  CHECK(!on_feed.pending());
  // A complete late frame is stale even without an explicit timeout call.
  Parser late;
  fake_ms = 12000;
  late.request_started(0x0604);
  fake_ms = 12500;
  CHECK(late.feed(OUTLET).empty());
  CHECK(late.timeouts() == 1);
  CHECK(late.stale_frames() == 1);
}

static void clock_rollover() {
  Parser p;
  fake_ms = std::numeric_limits<uint32_t>::max() - 100;
  p.request_started(0x0604);
  fake_ms = 149;  // 250 ms elapsed across rollover.
  const auto readings = p.feed(OUTLET);
  CHECK(readings.size() == 1);
  CHECK(readings[0].rtt_ms == 250);
  CHECK(p.last_seen(0x0604) == 149);
  CHECK(p.timeouts() == 0);

  Parser timeout;
  fake_ms = std::numeric_limits<uint32_t>::max() - 100;
  timeout.request_started(0x0604);
  fake_ms = 398;
  CHECK(!timeout.timeout_check());
  fake_ms = 399;
  CHECK(timeout.timeout_check());
  CHECK(timeout.timeouts() == 1);
  CHECK(timeout.feed(OUTLET).empty());
  CHECK(timeout.stale_frames() == 1);
}

static void control_echo_is_not_a_readback() {
  const Bytes increment{0x02, 0x55, 0x30, 0x03, '8', '8', 0x0D};
  const Bytes decrement{0x02, 0x55, 0x31, 0x03, '8', '9', 0x0D};
  Parser p;
  fake_ms = 20000;
  p.request_started(0x0604);
  CHECK(p.feed(increment).empty());
  CHECK(p.control_echo_frames() == 1);
  CHECK(p.pending());
  CHECK(p.valid_frames() == 0);
  CHECK(p.last_valid_ms() == 0);
  CHECK(p.bad_frames() == 0);
  CHECK(p.feed(Bytes(decrement.begin(), decrement.begin() + 3)).empty());
  CHECK(p.feed(Bytes(decrement.begin() + 3, decrement.end())).empty());
  CHECK(p.control_echo_frames() == 2);
  CHECK(p.pending());
  CHECK(p.valid_frames() == 0);
  auto wrong_checksum = increment;
  wrong_checksum[5] = '9';
  CHECK(p.feed(wrong_checksum).empty());
  CHECK(p.bad_frames() == 1);
  CHECK(p.control_echo_frames() == 2);
  CHECK(p.pending());
  CHECK(p.feed(OUTLET).size() == 1);
  CHECK(!p.pending());
  CHECK(p.valid_frames() == 1);
  CHECK(p.feed(decrement).empty());
  CHECK(p.control_echo_frames() == 3);
  CHECK(p.stale_frames() == 0);
}

int main() {
  real_captures();
  every_two_chunk_split();
  noise_echo_and_resynchronization();
  malformed_frames();
  pending_address_and_stale();
  timeout_boundaries();
  clock_rollover();
  control_echo_is_not_a_readback();
  std::cout << "PASS: " << checks << " checks across 8 telemetry parser scenarios\n";
}
