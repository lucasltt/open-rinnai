"""Embed the generated PWA and installer in flash, with deterministic gzip."""
from pathlib import Path
import gzip
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
dashboard = ROOT / "esphome/dashboard"
subprocess.run([sys.executable, str(ROOT / "analysis/build_pwa_assets.py")], check=True)
files = [
    ("app", "pwa/app.html", "text/html; charset=utf-8", ("/app", "/app/")),
    ("installer_js", "pwa.js", "application/javascript; charset=utf-8", ("/pwa.js",)),
    ("installer_css", "pwa.css", "text/css; charset=utf-8", ("/pwa.css",)),
    ("manifest", "pwa/manifest.webmanifest", "application/manifest+json; charset=utf-8", ("/manifest.webmanifest",)),
    ("worker", "pwa/sw.js", "application/javascript; charset=utf-8", ("/sw.js",)),
    ("apple", "pwa/icons/apple-touch-icon.png", "image/png", ("/apple-touch-icon.png", "/icons/apple-touch-icon.png")),
    ("icon192", "pwa/icons/icon-192.png", "image/png", ("/icons/icon-192.png",)),
    ("icon512", "pwa/icons/icon-512.png", "image/png", ("/icons/icon-512.png",)),
    ("maskable", "pwa/icons/maskable-512.png", "image/png", ("/icons/maskable-512.png",)),
]
lines = ["// Generated by analysis/embed_pwa_assets.py. Do not edit.", "#pragma once",
         "#include <cstddef>", "#include <cstdint>", "#include <cstring>", "namespace rinnai_pwa {",
         "struct Asset { const char *path; const char *type; const uint8_t *data; size_t size; bool compressed; };"]
rows = []
total = 0
for symbol, filename, mime, routes in files:
    raw = (dashboard / filename).read_bytes()
    compressed = not filename.endswith(".png")
    body = gzip.compress(raw, compresslevel=9, mtime=0) if compressed else raw
    total += len(body)
    lines.append(f"inline constexpr uint8_t {symbol}[] = {{")
    for offset in range(0, len(body), 24):
        lines.append("  " + ",".join(f"0x{value:02x}" for value in body[offset:offset + 24]) + ",")
    lines.append("};")
    for route in routes:
        rows.append(f'  {{"{route}", "{mime}", {symbol}, sizeof({symbol}), {str(compressed).lower()}}},')
lines.extend(["inline constexpr Asset ASSETS[] = {", *rows, "};",
              "inline const Asset *find(const char *path) {",
              "  for (const auto &asset : ASSETS) if (std::strcmp(path, asset.path) == 0) return &asset;",
              "  return nullptr;", "}", "}  // namespace rinnai_pwa", ""])
(dashboard / "pwa_assets.h").write_text("\n".join(lines), encoding="utf-8")
print(f"Embedded PWA: {len(rows)} routes, {total} flash bytes")
